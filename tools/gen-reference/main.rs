/// Where the committed copy lives, relative to the repository root.
const REFERENCE_PATH: &str = "reference.json";
/// The decode/signature conformance fixture, relative to the repository root.
const FIXTURE_PATH: &str = "tests/fixtures/tone.wav";

/// Seeds of the synthetic corpora. All five corpora are generated by
/// [`builder::voices_samples`] from these seeds; the values themselves
/// are pinned in `reference.json`, so a seed change fails `verify`
/// loudly instead of drifting silently.
const SEED_MONO: u64 = 0xC0_FFEE;
const SEED_CONTENT: u64 = 0xD1_CE;
const SEED_PREFIX: u64 = 0xBE_EF;
const SEED_FILLER: u64 = 0xE5_A5;
const SEED_OTHER: u64 = 0xF0_0D;
const SEED_STEREO_L: u64 = 0x11;
const SEED_STEREO_R: u64 = 0x22;

/// One decoded WAV measurement: the fields reference.json records for
/// every decode vector.
struct Decoded {
    sample_rate: u32,
    channels: u16,
    bits_per_sample: u16,
    frames: usize,
    decoded_samples: usize,
    /// The decoded canonical samples, when the vector pins them.
    samples: Vec<i32>,
    pcm_i32_le_sha256: String,
    pcm_i32_le_fnv1a64: String,
}

/// One extracted signature measurement.
struct Signed {
    frames: u32,
    peak_count: usize,
    /// `(t, f)` pairs in signature order.
    peaks: Vec<(u32, u16)>,
    fingerprint: u64,
}

/// Measures one WAV byte string through the public decode API.
fn measure(input: &[u8]) -> Decoded {
    let out = wav::decode(input).expect("vector input must decode");
    Decoded {
        sample_rate: out.sample_rate(),
        channels: out.channels(),
        bits_per_sample: out.bits_per_sample(),
        frames: out.frames(),
        decoded_samples: out.samples().len(),
        samples: out.samples().to_vec(),
        pcm_i32_le_sha256: hex(sha256(&pcm_le(out.samples()))
            .expect("sha256 of pcm")
            .as_bytes()),
        pcm_i32_le_fnv1a64: format!("{:016x}", fnv1a64(&pcm_le(out.samples()))),
    }
}

/// Measures interleaved PCM through the public signature API.
fn measure_signature(samples: &[i32], channels: u16) -> Signed {
    let sig = signature(samples, channels).expect("vector pcm must be accepted");
    signed(&sig)
}

/// Measures a WAV byte string through the `signature_of_wav` facade.
fn measure_signature_of_wav(input: &[u8]) -> Signed {
    let sig = signature_of_wav(input).expect("vector wav must be accepted");
    signed(&sig)
}

fn signed(sig: &Signature) -> Signed {
    Signed {
        frames: sig.frames(),
        peak_count: sig.len(),
        peaks: sig.peaks().iter().map(|p| (p.t, p.f)).collect(),
        fingerprint: sig.fingerprint(),
    }
}

/// Serializes peaks the way `peaks_sha256` hashes them: `u32`-LE `t`
/// then `u16`-LE `f`, one peak after another.
fn peaks_le(peaks: &[(u32, u16)]) -> Vec<u8> {
    let mut v = Vec::with_capacity(peaks.len() * 6);
    for &(t, f) in peaks {
        v.extend_from_slice(&t.to_le_bytes());
        v.extend_from_slice(&f.to_le_bytes());
    }
    v
}

fn pcm_le(samples: &[i32]) -> Vec<u8> {
    let mut v = Vec::with_capacity(samples.len() * 4);
    for &s in samples {
        v.extend_from_slice(&s.to_le_bytes());
    }
    v
}

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

/// The stable kind name a [`pith_digest::Error`] variant records as.
fn error_kind(e: &pith_digest::Error) -> &'static str {
    match e {
        pith_digest::Error::Truncated { .. } => "truncated",
        pith_digest::Error::InvalidMagic { .. } => "invalid-magic",
        pith_digest::Error::BadValue(_) => "bad-value",
        pith_digest::Error::Unsupported(_) => "unsupported",
        pith_digest::Error::TooLarge { .. } => "too-large",
    }
}

/// The stable kind name the facade's [`pith_audio::Error`] records as.
fn facade_error_kind(e: &pith_audio::Error) -> &'static str {
    match e {
        pith_audio::Error::BadValue(_) => "bad-value",
        pith_audio::Error::Unsupported(_) => "unsupported",
        pith_audio::Error::Decode(_) => "decode",
    }
}

