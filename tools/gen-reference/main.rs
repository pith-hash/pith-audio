/// 8-bit mono PCM centring: `0x00 -> -128`, `0x80 -> 0`, `0xFF -> 127`.
fn pcm8_offset_wav() -> Vec<u8> {
    pcm_wav(1, 1, 8_000, 8, &[0x00, 0x80, 0xFF, 0x01])
}

/// 24-bit sign extension, including the most negative sample
/// `00 00 80` and the positive max `FF FF 7F`.
fn pcm24_sign_extend_wav() -> Vec<u8> {
    pcm_wav(
        1,
        1,
        48_000,
        24,
        &[
            0x00, 0x00, 0x80, // -8388608
            0xFF, 0xFF, 0x7F, //  8388607
            0x00, 0x00, 0x00, //        0
            0xFF, 0xFF, 0xFF, //       -1
            0x00, 0x01, 0x00, //      256
        ],
    )
}

/// Float32 clamping endpoints and NaN mapping.
fn float32_clamp_wav() -> Vec<u8> {
    let mut data = Vec::new();
    for s in [0.0f32, -1.0, 1.0, 0.5, 1.5, f32::NAN] {
        data.extend_from_slice(&s.to_le_bytes());
    }
    pcm_wav(3, 1, 44_100, 32, &data)
}

/// Float64 exact halves and the pinned 1/3 rounding.
fn float64_thirds_wav() -> Vec<u8> {
    let mut data = Vec::new();
    for s in [0.25f64, -0.5, 1.0 / 3.0] {
        data.extend_from_slice(&s.to_le_bytes());
    }
    pcm_wav(3, 1, 44_100, 64, &data)
}

/// An odd-sized LIST chunk between `fmt ` and `data`: the pad byte
/// must be consumed for the walk to find `data`.
fn odd_chunk_pad_wav() -> Vec<u8> {
    wav_file(&[
        chunk(b"fmt ", &fmt_chunk(1, 1, 44_100, 16)),
        chunk(b"LIST", b"INFOX"),
        chunk(b"data", &[0x01, 0x00, 0xFE, 0xFF]),
    ])
}

/// A dangling byte after a whole 16-bit frame: dropped, never decoded.
fn partial_frame_wav() -> Vec<u8> {
    pcm_wav(1, 1, 8_000, 16, &[0x05, 0x00, 0xAA])
}

/// The mono signature corpus: 1.5 s of square-voice bursts.
fn mono_corpus() -> Vec<i32> {
    voices_samples(SEED_MONO, 66_150)
}

/// The offset-match scenario: the query is a 2 s prefix followed by
/// 3 s of indexed content, matched against a two-member index.
struct OffsetCorpus {
    query: Vec<i32>,
    corpus: Vec<Vec<i32>>,
    /// Exact expected modal offset in frames.
    expected_delta_t: f64,
}

fn offset_corpus() -> OffsetCorpus {
    let content = voices_samples(SEED_CONTENT, 132_300);
    let prefix = voices_samples(SEED_PREFIX, 88_200);
    let mut query = prefix;
    query.extend_from_slice(&content);
    let corpus = vec![
        content,
        voices_samples(SEED_OTHER, 132_300),
        voices_samples(SEED_FILLER, 44_100),
    ];
    OffsetCorpus {
        query,
        corpus,
        expected_delta_t: 88_200.0 / 2048.0,
    }
}

/// The stereo mixdown scenario: interleaved stereo content and its
/// explicit channel average — the pipeline's own mix must agree.
fn stereo_corpus() -> (Vec<i32>, Vec<i32>) {
    let stereo = voices_samples_stereo(SEED_STEREO_L, SEED_STEREO_R, 88_200);
    let mono = mono_average(&stereo, 2);
    (stereo, mono)
}

