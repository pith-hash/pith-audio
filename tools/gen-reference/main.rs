//! Regenerates and verifies `reference.json`, the hex-exact cross-SDK
//! test vectors for `pith-audio`.
//!
//! Every vector is computed through the crate's public API from inputs
//! that are either the committed conformance fixture
//! (`tests/fixtures/tone.wav`) or synthetic streams built byte-by-byte
//! here from [`pith_audio::reference`]'s SplitMix64 synthesis — no RNG
//! beyond the fixed SplitMix64 stream, no time, no transcendentals, no
//! platform-dependent bytes — so the output is byte-stable everywhere.
//!
//! Numeric policy: this crate's vectors record only *discrete* values
//! (integer PCM samples, peak `(t, f)` sets, fingerprints, hashes).
//! No raw `f64` spectrum bins are committed, so no per-vector float
//! tolerance policy is needed; the byte contract is exact everywhere.
//! The spectral peak decisions are separated by orders of magnitude
//! from the ulp-level trig drift any platform's `sin`/`cos` may show,
//! which the committed burst-shaped corpora guarantee by construction.
//!
//! Usage:
//! - `gen-reference gen` — recompute every vector and write
//!   `reference.json` at the repository root.
//! - `gen-reference verify` — recompute and compare byte-for-byte
//!   against the committed copy; exit 1 on drift. This is the CI gate.

